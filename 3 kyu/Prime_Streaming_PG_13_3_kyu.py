class Primes:
    @staticmethod
    def stream():
        yield 2
        sieve = {}
        n = 3
        while True:
            if n not in sieve:
                yield n
                sieve[n * n] = 2 * n  # Шаг для перехода к следующему нечетному кратному
            else:
                step = sieve[n]
                next_mult = n + step
                while next_mult in sieve:
                    next_mult += step
                sieve[next_mult] = step
                del sieve[n]
            n += 2




# 📚 САМОЕ ВАЖНОЕ: Что такое простые числа?
# Простое число — это число, которое делится только на 1 и на само себя.

# Примеры:

# ✅ 2 — делится на 1 и на 2 (простое)

# ✅ 3 — делится на 1 и на 3 (простое)

# ✅ 5 — делится на 1 и на 5 (простое)

# ❌ 4 — делится на 1, 2, 4 (НЕ простое, потому что делится на 2)

# ❌ 9 — делится на 1, 3, 9 (НЕ простое, потому что делится на 3)

# Наша задача — находить простые числа одно за другим и выдавать их.

# 🧠 Как работает этот код (общая идея)
# Представьте, что мы идем по числам: 2, 3, 4, 5, 6, 7, 8, 9, 10...

# Вместо того чтобы проверять каждое число (делится ли оно на что-то), мы запоминаем все числа, которые точно НЕ являются простыми (составные).

# Как мы их запоминаем? Когда находим простое число, мы вычисляем все его кратные (числа, которые делятся на него) и помечаем их как составные.

# Пример:

# Нашли простое число 3

# Помечаем: 9, 15, 21, 27, 33... — все эти числа составные

# Когда дойдем до 9, мы уже знаем, что оно составное, и пропускаем его

