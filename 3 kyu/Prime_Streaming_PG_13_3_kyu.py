class Primes:
    @staticmethod
    def stream():
        yield 2
        sieve = {}
        n = 3
        while True:
            if n not in sieve:
                yield n
                sieve[n * n] = [n]
            else:
                for p in sieve[n]:
                    next_mult = n + 2 * p
                    if next_mult in sieve:
                        sieve[next_mult].append(p)
                    else:
                        sieve[next_mult] = [p]
                del sieve[n]
            n += 2




# 🎯 Что делает код?
# Генерирует простые числа по одному: 2, 3, 5, 7, 11, 13, 17... и так до бесконечности.

# 🧱 Базовые понятия
# Что такое простое число?

# Число, которое делится только на 1 и на само себя

# Примеры: 2, 3, 5, 7, 11 (делятся только на 1 и на себя)

# Не простые: 4 (делится на 2), 6 (делится на 2 и 3), 9 (делится на 3)

