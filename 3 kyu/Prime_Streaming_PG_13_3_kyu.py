# Строка 3:
# python
# yield 2
# Первое простое число — 2. Мы его сразу отдаем. yield значит "выдать значение и подождать, пока попросят следующее".

# Строка 4:
# python
# sieve = {}
# Создаем пустой словарь (как записная книжка).
# Ключ → Значение.
# Здесь мы будем запоминать составные числа (не простые) и их "шаги".

# Строка 5:
# python
# n = 3
# Начинаем проверку с числа 3 (2 уже выдали). Дальше будем проверять только нечетные числа (3, 5, 7, 9...), потому что четные > 2 не могут быть простыми.

# Строка 6:
# python
# while True:
# Бесконечный цикл — будем генерировать числа вечно.

# Строка 7:
# python
# if n not in sieve:
# Спрашиваем: "Число n есть в нашей записной книжке (словаре)?"

# Если нет → значит это число еще не отмечено как составное → оно простое!

# Если да → значит это составное число, мы его уже отметили ранее

# Строки 8-9 (Число простое):
# python
# yield n
# sieve[n * n] = [n]
# yield n — выдаем простое число

# sieve[n * n] = [n] — запоминаем, что квадрат этого числа (n×n) будет составным.
# Например: n=3 → запоминаем, что 9 составное, и его "строитель" — 3

# Почему квадрат?
# Если число 3 простое, то его кратные (6, 9, 12, 15...) — составные.
# Но четные мы не проверяем (шаг 2), поэтому первое нечетное кратное 3, которое мы встретим — это 9 (3×3).

# Строки 10-16 (Число составное):
# python
# else:
#     for p in sieve[n]:
#         next_mult = n + 2 * p
#         if next_mult in sieve:
#             sieve[next_mult].append(p)
#         else:
#             sieve[next_mult] = [p]
#     del sieve[n]
# Это самое сложное место. Разберем на примере:

# Представьте: мы дошли до числа 9, и в словаре есть запись:

# python
# sieve[9] = [3]  # означает: 9 составное, его построило число 3
# Теперь по шагам:

# for p in sieve[n] — берем список "строителей". Для 9 это [3]

# next_mult = n + 2 * p — вычисляем следующее кратное:
# 9 + 2×3 = 9 + 6 = 15

# Запоминаем, что 15 тоже составное, и его построитель — 3:

# python
# sieve[15] = [3]
# del sieve[n] — удаляем 9 из словаря, она нам больше не нужна

# Зачем это делать?
# Мы как бы "передаем" информацию дальше: число 3 будет строить 15, потом 21, потом 27...
# Но мы пропускаем четные (потому что +6), и проверяем только нечетные числа.

# Строка 17:
# python
# n += 2
# Переходим к следующему нечетному числу:
# 3 → 5 → 7 → 9 → 11 → 13 → 15 → ...

# 🔍 Прогоним на примере первых чисел
# n	Что в словаре	Действие
# 2	{}	Выдаем 2
# 3	{}	3 нет в словаре → простое! Запоминаем: sieve[9]=[3]
# 5	{9:[3]}	5 нет → простое! Запоминаем: sieve[25]=[5]
# 7	{9:[3], 25:[5]}	7 нет → простое! Запоминаем: sieve[49]=[7]
# 9	{9:[3], 25:[5], 49:[7]}	9 есть в словаре → составное! Берем 3, вычисляем 9+6=15, запоминаем sieve[15]=[3]. Удаляем 9
# 11	{15:[3], 25:[5], 49:[7]}	11 нет → простое! Запоминаем sieve[121]=[11]
# 13	{15:[3], 25:[5], 49:[7], 121:[11]}	13 нет → простое! Запоминаем sieve[169]=[13]
# 15	{15:[3], 25:[5], 49:[7], 121:[11], 169:[13]}	15 есть → составное! Берем 3, вычисляем 15+6=21, запоминаем sieve[21]=[3]. Удаляем 15
# 🤔 Почему это работает?
# Мы не проверяем каждое число на делимость (это медленно).
# Вместо этого мы запоминаем все составные числа заранее, используя простые числа как "строителей".

# Аналогия:
# Представьте, что вы вычеркиваете в таблице все числа, кратные 3, 5, 7...
# Но вместо таблицы на миллион чисел, вы используете словарь и запоминаете только те составные числа, которые вам скоро понадобятся.

# 💡 Почему n * n и n + 2 * p?
# n * n — первое нечетное кратное n, которое мы встретим (потому что мы идем с шагом 2)

# n + 2 * p — следующее нечетное кратное после текущего

# Пример для p=3:

# 3×3 = 9 (первое нечетное кратное)

# 9 + 6 = 15 (следующее нечетное кратное)

# 15 + 6 = 21 (и так далее)

# 📊 Итог
# Код работает как конвейер:

# Берем число

# Проверяем, не записано ли оно как составное

# Если нет → выдаем как простое и планируем его кратные в будущем

# Если да → переносим его "строителя" на следующее кратное и забываем о нем

# Это очень эффективно, потому что мы не храним все числа, а только те, которые скоро понадобятся!
